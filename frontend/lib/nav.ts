const norm = (p: string) => (p.split('?')[0].replace(/\/+$/, '') || '/').toLowerCase()

/** Which top-level menu section a page belongs to (used for the sidebar and breadcrumbs). */
export function sectionFor(path: string): NavSection | undefined {
  const p = norm(path)
  for (const s of NAV) for (const g of s.groups) for (const l of g.links) if (norm(l.href) === p) return s
  if (p.startsWith('/training') || p === '/certification-card-request') return NAV[0]
  if (p.startsWith('/sweepstakes') || p.startsWith('/fan-education')) return NAV[1]
  if (p.startsWith('/about/') && /meeting|member|stakeholder|events-fy|committee|webinar|vote/.test(p)) return NAV[2]
  if (p.startsWith('/news') || p.startsWith('/media-mentions') || p.startsWith('/newsletter') || p.startsWith('/posts')) return NAV[3]
  if (p.startsWith('/about') || p === '/team-101' || p === '/contact') return NAV[4]
  return undefined
}
